function normalizeLocale(value) {
  if (typeof value !== 'string') return null;
  const input = value.trim();
  if (!input) return null;
  const lower = input.toLowerCase();
  if (lower === 'zh-cn' || lower === 'zh_cn') return 'zh-CN';
  if (lower === 'en') return 'en';
  return null;
}

function readPath(object, key) {
  return key.split('.').reduce((current, part) => {
    if (!current || typeof current !== 'object' || !Object.prototype.hasOwnProperty.call(current, part)) {
      return undefined;
    }
    return current[part];
  }, object);
}

export function resolveLocale({ search, stored } = {}) {
  const queryLocale = normalizeLocale(typeof search === 'string' ? new URLSearchParams(search).get('lang') : null);
  if (queryLocale) return queryLocale;
  const storedLocale = normalizeLocale(stored);
  if (storedLocale) return storedLocale;
  return defaultLocale;
}

export function translate(locale, key, params = {}) {
  const normalized = normalizeLocale(locale) || defaultLocale;
  const catalog = catalogs[normalized] || catalogs[defaultLocale];
  let value = Object.prototype.hasOwnProperty.call(catalog, key) ? catalog[key] : readPath(catalog, key);
  if (value === undefined && normalized !== defaultLocale) {
    const fallbackCatalog = catalogs[defaultLocale];
    value = Object.prototype.hasOwnProperty.call(fallbackCatalog, key) ? fallbackCatalog[key] : readPath(fallbackCatalog, key);
  }
  if (value === undefined) return key;
  if (typeof value === 'function') return value(params, normalized);
  return String(value).replace(/\{(\w+)\}/g, (_, token) => {
    const replacement = params[token];
    return replacement === undefined || replacement === null ? '' : String(replacement);
  });
}

function canUseBrowser() {
  return typeof window !== 'undefined' && typeof document !== 'undefined';
}

function getStoredLocale() {
  if (!canUseBrowser()) return null;
  try {
    return window.localStorage.getItem(languageStorageKey);
  } catch (error) {
    if (error.name !== 'SecurityError') throw error;
    console.warn('Language preference storage is unavailable; using the URL or default locale.');
    return null;
  }
}

function persistLocale(locale) {
  if (!canUseBrowser()) return;
  try {
    window.localStorage.setItem(languageStorageKey, locale);
  } catch (error) {
    if (!['SecurityError', 'QuotaExceededError'].includes(error.name)) throw error;
    console.warn('Language preference could not be stored; the selected language remains in the URL.');
  }
}

function syncDocument(locale) {
  if (!canUseBrowser()) return;
  document.documentElement.lang = locale;
  document.title = translate(locale, 'head.title');
  const description = document.querySelector('meta[name="description"]');
  if (description) description.setAttribute('content', translate(locale, 'head.description'));
}

function syncUrl(locale) {
  if (!canUseBrowser()) return;
  const url = new URL(window.location.href);
  url.searchParams.set('lang', locale);
  window.history.replaceState(window.history.state, '', `${url.pathname}${url.search}${url.hash}`);
}

let currentLocale = canUseBrowser()
  ? resolveLocale({ search: window.location.search, stored: getStoredLocale() })
  : defaultLocale;

syncDocument(currentLocale);

const listeners = new Set();

export function getLocale() {
  return currentLocale;
}

export function setLocale(nextLocale, { persist = true, syncLocation = true } = {}) {
  const normalized = normalizeLocale(nextLocale) || defaultLocale;
  currentLocale = normalized;
  if (canUseBrowser()) {
    if (persist) persistLocale(normalized);
    if (syncLocation) syncUrl(normalized);
    syncDocument(normalized);
  }
  for (const listener of listeners) listener();
  return normalized;
}

export function subscribeLocale(listener) {
  listeners.add(listener);
  return () => listeners.delete(listener);
}

export function localeLabel(locale) {
  return normalizeLocale(locale) || defaultLocale;
}
